/**
 * Loaded UI strings. Other languages live in utils/locales/<code>.ts and are
 * fetched on demand with loadLanguage(), so they don't bloat the main bundle.
 */
export const UI_STRINGS: Partial<Record<LanguageCode, Record<string, string>>> = { 'en-US': EN_US };

const LOADERS: Record<Exclude<LanguageCode, 'en-US'>, () => Promise<{ default: Record<string, string> }>> = {
  es: () => import('./locales/es'),
  fr: () => import('./locales/fr'),
  de: () => import('./locales/de'),
  zh: () => import('./locales/zh'),
  ja: () => import('./locales/ja'),
  uk: () => import('./locales/uk'),
  pt: () => import('./locales/pt'),
  it: () => import('./locales/it'),
  ru: () => import('./locales/ru'),
  ko: () => import('./locales/ko'),
  ar: () => import('./locales/ar'),
  hi: () => import('./locales/hi'),
};

export const isLanguageLoaded = (lang: LanguageCode) => !!UI_STRINGS[lang];

/** Fetch a language's strings (no-op if already loaded). Falls back to English on failure. */
export const loadLanguage = async (lang: LanguageCode): Promise<void> => {
  if (UI_STRINGS[lang] || !(lang in LOADERS)) return;
  try {
    UI_STRINGS[lang] = (await LOADERS[lang as Exclude<LanguageCode, 'en-US'>]()).default;
  } catch (e) {
    console.warn('[i18n] Could not load language', lang, e);
  }
};

/** Looks up a UI string: current language, then English, then English strings not yet merged (utils/i18n), then the key. */
export const t = (lang: LanguageCode, key: string): string => {
  return UI_STRINGS[lang]?.[key] || UI_STRINGS['en-US'][key] || EXTRA_EN[key] || key;
};
